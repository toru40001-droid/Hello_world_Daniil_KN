print("Стоит витязь на распутье у камня вещего...")
print("На камне том надпись:")
print("  Прямо поедешь - живу не бывати")
print("  Направо поедешь - женату быти")
print("  Налево поедешь - богату быти")

выбор = input("Куда направить путь? (прямо/направо/налево): ").strip().lower()

if выбор == "прямо" or выбор == "прямо поедешь":
    print("\nПоехал витязь прямо...")
    print("Живу не бывати - нет пути ни прохожему, ни проезжему, ни пролётному.")
    print("Ждут его тьма, погибель и вечный покой на безжизненной пустоши.")
    print("Кости людские кругом, ворон чёрный кружит - знать, не вернуться ему назад.")

elif выбор == "направо" or выбор == "направо поедешь":
    print("\nПоехал витязь направо...")
    print("Женату быти - встретит он девицу красную, красоты невиданной.")
    print("Сыграют свадьбу, родят детей, построят дом.")
    print("Но не вечно счастье людское - быть может, в том счастье и погибель его?")

elif выбор == "налево" or выбор == "налево поедешь":
    print("\nПоехал витязь налево...")
    print("Богату быти - ждут его злато-серебро, каменья самоцветные.")
    print("Будет он богаче всех князей, да только богатство то - не от чистого сердца.")
    print("А ну как проклято то золото? Погубит оно душу его?")

else:
    print("\nНе стал витязь выбирать ни один из путей...")
    print("Стоит он у камня, думу думает, места себе не находит.")
    print("А время идёт, силы тают, и никто не знает, что ждёт его впереди.")
    print("Может, выбор - это и есть судьба его?")