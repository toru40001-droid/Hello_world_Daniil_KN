# Инициализация переменной для хранения суммы
sum_even = 0

# Цикл for перебирает числа в диапазоне от 1 до 15
# range(1, 16) означает, что последнее число (16) не включается
for i in range(1, 16):
    # Проверка на чётность: остаток от деления на 2 должен быть равен 0
    if i % 2 == 0:
        # Прибавление чётного числа к общей сумме
        sum_even += i

# Вывод итогового результата
print("Сумма чётных чисел:", sum_even)