# Инициализация векторов (списков)
a = [1, 2, 3]
b = [4, 5, 6]

# Определение длины вектора
n = len(a)

# Переменная для накопления результата
scalar = 0

# Цикл for проходит по индексам от 0 до n-1
for i in range(n):
    # Умножаем соответствующие элементы и прибавляем к сумме
    scalar = scalar + a[i] * b[i]

# Вывод результата
print("Скалярное произведение двух векторов:", scalar)