# Исходный массив из задания
array = [7, 3, 8, 1, 4, 6, 2, 5]
n = len(array)

# Внешний цикл отвечает за количество проходов по массиву
for i in range(n):
    # Флаг для оптимизации: была ли перестановка на этом этапе?
    swapped = False
    
    # Внутренний цикл сравнивает соседние элементы
    # Используем n - i - 1, чтобы не проверять уже отсортированные элементы в конце
    for j in range(0, n - i - 1):
        # Если левый элемент больше правого — меняем их местами
        if array[j] > array[j + 1]:
            # Python-способ обмена значений элементов
            array[j], array[j + 1] = array[j + 1], array[j]
            swapped = True
            
    # Если за весь проход перестановок не было — выходим из цикла досрочно
    if not swapped:
        break

# Вывод итогового результата
print("Отсортированный массив:", array)