# Инициализация векторов (списков)
a = [1, 2, 3]
b = [4, 5, 6]

# Определение длины вектора
n = len(a)

# Инициализация счетчика и переменной для результата
i = 0
scalar = 0

# Цикл while выполняется, пока индекс i меньше длины вектора n
while i < n:
    # Умножаем соответствующие элементы и прибавляем к накопленной сумме
    scalar = scalar + a[i] * b[i]
    # Обязательное увеличение счетчика для перехода к следующему элементу
    i = i + 1

# Вывод итогового результата
print("Скалярное произведение двух векторов:", scalar)